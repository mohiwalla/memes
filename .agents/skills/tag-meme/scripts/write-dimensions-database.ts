import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

type Options = {
	assetsDir: string
	outPath: string
}

type Dimensions = { w: number; h: number }

const parseArgs = (): Options => {
	const args = process.argv.slice(2)
	const getArg = (name: string, fallback: string) => {
		const index = args.indexOf(name)
		return index === -1 ? fallback : (args[index + 1] ?? fallback)
	}

	return {
		assetsDir: getArg("--assets-dir", "public/assets"),
		outPath: getArg("--out-path", "src/lib/memes-dimensions.ts"),
	}
}

const readPng = (buf: Buffer): Dimensions | null =>
	buf.toString("ascii", 1, 4) === "PNG"
		? { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) }
		: null

const readGif = (buf: Buffer): Dimensions | null =>
	buf.toString("ascii", 0, 3) === "GIF"
		? { w: buf.readUInt16LE(6), h: buf.readUInt16LE(8) }
		: null

const readWebp = (buf: Buffer): Dimensions | null => {
	if (buf.toString("ascii", 0, 4) !== "RIFF") return null
	if (buf.toString("ascii", 8, 12) !== "WEBP") return null

	const chunk = buf.toString("ascii", 12, 16)
	if (chunk === "VP8X") {
		return {
			w: 1 + buf.readUIntLE(24, 3),
			h: 1 + buf.readUIntLE(27, 3),
		}
	}
	if (chunk === "VP8L") {
		const bits = buf.readUInt32LE(21)
		return { w: 1 + (bits & 0x3fff), h: 1 + ((bits >> 14) & 0x3fff) }
	}
	if (chunk === "VP8 ") {
		return {
			w: buf.readUInt16LE(26) & 0x3fff,
			h: buf.readUInt16LE(28) & 0x3fff,
		}
	}

	return null
}

const readJpeg = (buf: Buffer): Dimensions | null => {
	if (buf[0] !== 0xff || buf[1] !== 0xd8) return null

	let offset = 2
	while (offset < buf.length) {
		if (buf[offset] !== 0xff) return null
		const marker = buf[offset + 1]
		const length = buf.readUInt16BE(offset + 2)
		const isStartOfFrame =
			marker >= 0xc0 &&
			marker <= 0xcf &&
			marker !== 0xc4 &&
			marker !== 0xc8 &&
			marker !== 0xcc
		if (isStartOfFrame) {
			return {
				w: buf.readUInt16BE(offset + 7),
				h: buf.readUInt16BE(offset + 5),
			}
		}
		offset += 2 + length
	}

	return null
}

// Truncated or malformed headers throw on fixed-offset reads; treat them as
// unknown so one bad asset does not stop the whole run.
const readDimensions = (buf: Buffer) => {
	try {
		return readPng(buf) ?? readGif(buf) ?? readWebp(buf) ?? readJpeg(buf)
	} catch {
		return null
	}
}

const options = parseArgs()
const dimensions: Record<string, Dimensions> = {}

for (const file of readdirSync(options.assetsDir).sort((a, b) =>
	a.localeCompare(b),
)) {
	const size = readDimensions(readFileSync(join(options.assetsDir, file)))
	if (!size || !size.w || !size.h) {
		console.warn(`skip ${file}: unknown image format`)
		continue
	}
	dimensions[file] = size
}

const lines = [
	"// Generated by .agents/skills/tag-meme/scripts/write-dimensions-database.ts",
	"export const MEMES_DIMENSIONS: Record<string, { w: number; h: number }> = {",
	...Object.entries(dimensions).map(
		([file, { w, h }]) =>
			`\t${JSON.stringify(file)}: { w: ${w}, h: ${h} },`,
	),
	"}",
	"",
]

writeFileSync(options.outPath, lines.join("\n"))
Bun.spawnSync(["bunx", "prettier", "--write", options.outPath])
console.log(
	`wrote ${Object.keys(dimensions).length} entries to ${options.outPath}`,
)
